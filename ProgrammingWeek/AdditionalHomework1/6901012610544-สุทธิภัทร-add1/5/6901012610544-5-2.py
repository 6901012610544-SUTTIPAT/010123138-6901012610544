def check_values():
    data = [300, 800, 600, 400, 300, 900, 550, 650, 420, 601]
    i = 0
    while i < len(data):
        if data[i] > 500:
            print(f"แจ้งเตือน: ค่า {data[i]} มีค่าเกิน 500")
        i = i + 1


check_values()